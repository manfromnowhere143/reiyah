    def test_omitted_extra_and_duplicate_comparison_anchors_are_not_subsets(self):
        self.package(); original = read(self.request['comparison']); normals = read(self.request['normalizations'])
        for defect in ('omitted', 'extra', 'duplicate'):
            with self.subTest(defect=defect):
                case, receipts = deepcopy(original), deepcopy(normals)
                if defect == 'omitted': case['anchors'].pop(); receipts.pop()
                else:
                    case['anchors'].append(deepcopy(case['anchors'][0])); receipts.append(deepcopy(receipts[0]))
                    if defect == 'extra':
                        catalog = read(self.request['catalog'])
                        extra, receipt = nuscenes.normalize_frame(
                            sample_token='f0-3', anchor_id='extra', ego_xy=[10, 20], weight=Fraction(1, 3),
                            base={'state': 'observed', 'value': [r for r in read(catalog['sources']['base']) if r['sample_token'] == 'f0-3']},
                            camera={'state': 'observed', 'value': [r for r in read(catalog['sources']['camera']) if r['sample_token'] == 'f0-3']},
                            source_sha256=receipts[0]['source_sha256'])
                        case['anchors'][-1] = extra; receipts[-1] = receipt
                for anchor, receipt in zip(case['anchors'], receipts):
                    anchor['weight'] = decision.wire(Fraction(1, len(case['anchors'])))
                    receipt['normalized_anchor_sha256'] = hashlib.sha256(decision.encoded(anchor)).hexdigest()
                replace(self.request, 'comparison', case); replace(self.request, 'normalizations', receipts)
                self.rejected('DUPLICATE_ID' if defect == 'duplicate' else 'BINDING_POPULATION')

    def test_duplicate_window_and_omitted_window_rejected(self):
        w = read(self.observation['window_report']); g = read(self.observation['geometry_report'])
        for report in (w, g): report['windows'].append(deepcopy(report['windows'][0]))
        replace(self.observation, 'window_report', w); g['inputs']['window_report'] = self.observation['window_report']
        replace(self.observation, 'geometry_report', g)
        self.rejected('OBS_BINDING', self.package)
        # A valid one-window package, with its capture union reduced consistently.
        for report in (w, g): report['windows'] = report['windows'][:1]
        tokens = {r['sample_data_token'] for r in g['windows'][0]['captures']}
        g['captures'] = {k: v for k, v in g['captures'].items() if k in tokens}
        replace(self.observation, 'window_report', w); g['inputs']['window_report'] = self.observation['window_report']
        replace(self.observation, 'geometry_report', g)
        self.package(); self.rejected('BINDING_POPULATION')

    def test_missing_and_other_nondelivered_states_are_preserved(self):
        inv = read(self.observation['inventory']); one, two, three, four, five = inv['assets'][:5]
        (self.root/'raw'/one['filename']).unlink()
        inv['assets'][1] = {'filename': two['filename'], 'state': 'unavailable', 'reason': 'not supplied'}
        inv['assets'].remove(three)
        (self.root/'raw'/four['filename']).write_bytes(b'corrupt')
        data = struct.pack('<5f', 1, 2, 3, 4, float('nan'))
        (self.root/'raw'/five['filename']).write_bytes(data)
        five.update(byte_size=len(data), sha256=hashlib.sha256(data).hexdigest())
        replace(self.observation, 'inventory', inv)
        w = read(self.observation['window_report']); w['inputs']['inventory'] = self.observation['inventory']
        rebind_window(self.observation, w)
        self.package(); report = binding.build(self.request)
        self.assertEqual(report['summary']['evidence_states'],
                         {'delivered': 65, 'missing': 1, 'unavailable': 1, 'not_listed': 1, 'invalid': 1, 'sensor_invalid': 1})
        self.assertEqual(len(report['captures']), 70)
        absent = [r for r in report['captures'] if r['source_content_check'] == 'not_delivered']
        self.assertEqual(len(absent), 5); self.assertTrue(all(r['delivered_source_body'] is None for r in absent))

