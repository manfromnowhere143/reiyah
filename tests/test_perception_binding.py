    def test_resealed_valid_substitute_jpeg_and_lidar_rejected_against_original_inventory(self):
        for channel in ('CAM_FRONT', 'LIDAR_TOP'):
            with self.subTest(channel=channel):
                self.package(); m = json.loads((self.out/'manifest.json').read_bytes())
                record = next(r for r in m['captures'] if r['channel'] == channel)
                if channel == 'LIDAR_TOP':
                    data, count = formats.lidar(struct.pack('<10f', 9, 8, 7, 6, 5, 4, 3, 2, 1, 0))
                    record['evidence']['point_count'] = count
                else:
                    from PIL import Image
                    buffer = io.BytesIO(); Image.new('RGB', (4, 3), (200, 100, 50)).save(buffer, format='JPEG')
                    data = buffer.getvalue()
                asset = record['evidence']['asset']; (self.out/asset['filename']).write_bytes(data)
                record['evidence']['asset'] = package.descriptor(asset['filename'], data)
                self.reseal(m); self.rejected('BINDING_ASSET')

