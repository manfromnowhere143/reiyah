def prepare(root):
    observation = fixture(root)
    windows = read(observation['window_report'])
    catalog_spec = windows['inputs']['catalog']
    catalog = read(catalog_spec)
    source_hashes = {'clock': catalog['sources']['metadata']['sha256']}
    # Small, actual source-byte identities; normalized rows are independently
    # generated by the established adapter, not assembled by the binding checker.
    for role, offset in [('base', 0), ('camera', 3)]:
        rows = [{'sample_token': w['sample_token'], 'detection_name': 'car', 'detection_score': 1,
                 'translation': [10+offset, 20, 0]} for w in catalog['anchors']]
        spec = identity_file(root/(role+'.json'), decision.encoded(rows))
        catalog['sources'][role] = spec | {'state': 'observed'}
        source_hashes[role] = spec['sha256']
    for row in catalog['anchors']:
        row['nominal_ego_xy'] = {'state': 'observed', 'timestamp_us': row['anchor_timestamp_us'], 'value': xy(10, 20)}
    catalog_spec = identity_file(Path(catalog_spec['path']), decision.encoded(catalog))
    windows['inputs']['catalog'] = catalog_spec
    rebind_window(observation, windows)
    geometry = read(observation['geometry_report']); geometry['inputs']['catalog'] = catalog_spec
    replace(observation, 'geometry_report', geometry)
    case = inputs(2)[1]; case['anchors'] = []; normalizations = []
    for w in windows['windows']:
        sample = w['sample_token']
        anchor, normalization = nuscenes.normalize_frame(
            sample_token=sample, anchor_id=w['anchor_id'], ego_xy=[10, 20], weight=Fraction(1, 2),
            base={'state': 'observed', 'value': [r for r in read(catalog['sources']['base']) if r['sample_token'] == sample]},
            camera={'state': 'observed', 'value': [r for r in read(catalog['sources']['camera']) if r['sample_token'] == sample]},
            source_sha256=source_hashes)
        case['anchors'].append(anchor); normalizations.append(normalization)
    request = {'artifact_id': 'reiyah.perception-binding.request', 'version': '0.1.0',
               'comparison': identity_file(root/'comparison.json', decision.encoded(case)),
               'normalizations': identity_file(root/'normalizations.json', decision.encoded(normalizations)),
               'catalog': catalog_spec}
    return observation, request


class BindingTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.observation, self.request = prepare(self.root)
        self.serial = 0

    def package(self):
        self.serial += 1
        self.out = self.root/f'package-{self.serial}'
        custody = self.root/f'custody-{self.serial}.json'
        result = package.build(self.observation, self.out, custody)
        self.request['observation_custody'] = identity_file(custody, custody.read_bytes())
        self.request['package'] = {'path': str(self.out), 'seal_sha256': result['seal_sha256']}
        return result

    def rejected(self, code, fn=None):
        with self.assertRaises(decision.Invalid) as caught:
            (fn or (lambda: binding.build(self.request)))()
        self.assertEqual(caught.exception.code, code)

    def reseal(self, manifest):
        # Rebuild both the package seal and custody as a plausible substitution.
        # The original inventory and source reports retain their selected bytes.
        data = decision.encoded(manifest); (self.out/'manifest.json').write_bytes(data)
        seal = json.loads((self.out/'SEAL.json').read_bytes())
        seal['manifest'] = package.descriptor('manifest.json', data)
        raw = decision.encoded(seal); (self.out/'SEAL.json').write_bytes(raw)
        sha = hashlib.sha256(raw).hexdigest(); self.request['package']['seal_sha256'] = sha
        custody = read(self.request['observation_custody']); custody['expected_seal_sha256'] = sha
        for row, evidence in zip(custody['captures'], manifest['captures']):
            row['disclosed_evidence'] = evidence['evidence']
        custody['summary'] = package.contract.validate(manifest)
        replace(self.request, 'observation_custody', custody)
        self.assertTrue(package.verify(self.out, sha)['disclosure_verified'])

    def test_exact_population_assets_and_deterministic_report_without_claim_promotion(self):
        self.package(); before = tree(self.out)
        report = binding.build(self.request)
        self.assertEqual(report['windows'], [
            {'window_id': 'window-0001', 'anchor_id': 'one', 'sample_token': 'f0-2',
             'scene_token': 's0', 'anchor_timestamp_us': 3_000_000},
            {'window_id': 'window-0002', 'anchor_id': 'two', 'sample_token': 'f1-2',
             'scene_token': 's1', 'anchor_timestamp_us': 13_000_000}])
        self.assertEqual(report['summary']['evidence_states'], {'delivered': 70})
        self.assertTrue(all(r['source_content_check'] == 'matched' for r in report['captures']))
        for r in report['captures']:
            # Direct original-file comparison, without projection or PLY helpers.
            original = (self.root/'raw'/r['source']['filename']).read_bytes()
            self.assertEqual(r['delivered_source_body'], {'byte_size': len(original),
                             'sha256': hashlib.sha256(original).hexdigest()})
        self.assertEqual(decision.encoded(report), decision.encoded(binding.build(self.request)))
        self.assertFalse(report['reference_constraints_admitted']); self.assertFalse(report['decision_evaluated'])
        self.assertEqual(report['physical_reference_coverage'], 'not_established')
        self.assertEqual(report['human_review'], 'not_established'); self.assertFalse(report['study_selection_performed'])
        self.assertEqual(tree(self.out), before)

    def test_wrong_valid_package_anchor_rejected(self):
        w = read(self.observation['window_report']); w['windows'][0]['anchor_id'] = 'different-anchor'
        rebind_window(self.observation, w)
        g = read(self.observation['geometry_report']); g['windows'][0]['anchor_id'] = 'different-anchor'
        replace(self.observation, 'geometry_report', g)
        result = self.package()
        self.assertTrue(package.verify(self.out, result['seal_sha256'])['disclosure_verified'])
        self.rejected('BINDING_POPULATION')

    def test_same_anchor_different_sample_or_scene_rejected(self):
        for defect in ('sample', 'scene'):
            with self.subTest(defect=defect):
                w = read(self.observation['window_report']); g = read(self.observation['geometry_report'])
                if defect == 'sample':
                    w['windows'][0]['sample_token'] = g['windows'][0]['sample_token'] = 'f0-3'
                else:
                    w['windows'][0]['sample_token'] = g['windows'][0]['sample_token'] = 'f0-2'
                    w['windows'][0]['scene_token'] = 's1'
                replace(self.observation, 'window_report', w)
                g['inputs']['window_report'] = self.observation['window_report']
                replace(self.observation, 'geometry_report', g)
                self.package(); self.rejected('BINDING_POPULATION')

    def test_identical_neutral_package_at_shifted_absolute_clock_is_rejected(self):
        self.package(); original = tree(self.out)
        w = read(self.observation['window_report']); g = read(self.observation['geometry_report'])
        for report in (w, g):
            for window in report['windows']:
                window['anchor_timestamp_us'] += 1
                window['context_window_us'] = [t+1 for t in window['context_window_us']]
        for window in w['windows']:
            for group in window['channels'].values():
                for capture in group['captures']: capture['capture_timestamp_us'] += 1
        for capture in g['captures'].values(): capture['capture_timestamp_us'] += 1
        replace(self.observation, 'window_report', w)
        g['inputs']['window_report'] = self.observation['window_report']
        replace(self.observation, 'geometry_report', g)
        self.package(); self.assertEqual(tree(self.out), original)
        self.rejected('BINDING_POPULATION')

    def test_catalog_and_metadata_identity_changes_rejected(self):
        original_w = read(self.observation['window_report']); original_g = read(self.observation['geometry_report'])
        for report_role, source_role, field, value in [
                ('window_report', 'catalog', 'sha256', 'f'*64),
                ('geometry_report', 'catalog', 'byte_size', 1),
                ('window_report', 'metadata', 'sha256', 'e'*64),
                ('geometry_report', 'metadata', 'byte_size', True)]:
            with self.subTest(report=report_role, source=source_role, field=field):
                w, g = deepcopy(original_w), deepcopy(original_g)
                (w if report_role == 'window_report' else g)['inputs'][source_role][field] = value
                replace(self.observation, 'window_report', w); g['inputs']['window_report'] = self.observation['window_report']
                replace(self.observation, 'geometry_report', g)
                self.package(); self.rejected('BINDING_SOURCE')

